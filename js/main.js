const ROUTES=['home','projects','services','areas','about','asbestos','emergency','privacy','terms','cookies','contact','404'];
function route(){
  const h=(location.hash||'#home').slice(1);
  const r=(!location.hash||h==='home')?'home':(ROUTES.includes(h)?h:'404');
  ROUTES.forEach(n=>{$('#p-'+n).hidden=n!==r});
  $$('.nav a[data-route]').forEach(a=>{if(a.dataset.route===r)a.setAttribute('aria-current','page');else a.removeAttribute('aria-current')});
  $('#nav').classList.remove('open');$('#burger').setAttribute('aria-expanded','false');
  window.scrollTo(0,0);
}
$('#burger').addEventListener('click',()=>{const o=$('#nav').classList.toggle('open');$('#burger').setAttribute('aria-expanded',o)});
window.addEventListener('hashchange',route);

